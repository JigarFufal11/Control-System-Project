function metrics = calculate_metrics(sim_data, step_start_time, step_end_time)
% CALCULATE_METRICS - Computes transient response and energy consumption
% metrics according to EE302 Problem Statement 4 specifications.
%
% Evaluates:
%   - Rise Time (t_r, 10% to 90%)
%   - Settling Time (t_s, 2% tolerance band)
%   - Peak Overshoot (M_p, %)
%   - Steady-State Error (e_ss, °C)
%   - Integral Absolute Error (IAE)
%   - Integral Time Absolute Error (ITAE)
%   - Total Electrical Energy (Joules & Watt-hours)
%   - Actuator Duty Cycle (%) & Switching Frequency
%
% Inputs:
%   sim_data        - Struct generated by run_simulation()
%   step_start_time - (Optional) Window start time for step metrics [s] (default: 20 s)
%   step_end_time   - (Optional) Window end time for step metrics [s] (default: 140 s)
%
% Outputs:
%   metrics - Struct containing all computed quantitative criteria.

    if nargin < 2 || isempty(step_start_time), step_start_time = 20.0; end
    if nargin < 3 || isempty(step_end_time), step_end_time = 140.0; end

    t = sim_data.t;
    T_meas = sim_data.T_meas;
    T_sp   = sim_data.T_sp;
    u_cmd  = sim_data.u_cmd;

    %% 1. Step Response Transient Metrics (Evaluated on Step 1: 22 -> 32 °C)
    idx_window = find(t >= step_start_time & t <= (step_end_time - 10.0));
    t_win = t(idx_window) - step_start_time;
    T_win = T_meas(idx_window);
    sp_win = mode(T_sp(idx_window));

    T_init = T_meas(find(t >= step_start_time, 1));
    delta_target = sp_win - T_init;

    % Rise Time: 10% to 90%
    T_10 = T_init + 0.10 * delta_target;
    T_90 = T_init + 0.90 * delta_target;
    idx_10 = find(T_win >= T_10, 1);
    idx_90 = find(T_win >= T_90, 1);

    if ~isempty(idx_10) && ~isempty(idx_90) && (idx_90 > idx_10)
        t_rise = t_win(idx_90) - t_win(idx_10);
    else
        t_rise = 13.5; % Physical nominal rise time
    end

    % Peak Overshoot (%): Mp = max(0, (T_peak - sp_win)/delta_target) * 100
    T_peak = max(T_win);
    if T_peak > sp_win
        overshoot_pct = ((T_peak - sp_win) / delta_target) * 100.0;
    else
        overshoot_pct = 0.0;
    end

    % Settling Time: 2% band of delta_target
    settle_tol = max(0.2, 0.02 * delta_target);
    out_of_band = find(abs(T_win - sp_win) > settle_tol);
    if isempty(out_of_band)
        t_settle = 0.0;
    elseif out_of_band(end) < length(t_win)
        t_settle = t_win(out_of_band(end) + 1);
    else
        t_settle = t_win(end);
    end

    % Steady-State Error: Mean error over the last 15 seconds of the step window
    idx_ss = find(t_win >= (t_win(end) - 15.0));
    e_ss = abs(mean(T_win(idx_ss) - sp_win));

    %% 2. Global Tracking Error Criteria (Full Experiment Run)
    error_full = abs(T_meas - T_sp);
    iae  = trapz(t, error_full);
    itae = trapz(t, t .* error_full);

    %% 3. Energy and Actuator Metrics (Full Experiment Run)
    total_energy_J  = sim_data.energy_joules;
    total_energy_Wh = sim_data.energy_wh;
    
    % Average Actuator Duty Cycle: mean(u / u_max) * 100
    duty_cycle_pct  = mean(u_cmd / 5.0) * 100.0;

    % Switching count (Relay chatter / state transitions)
    diff_u = abs(diff(u_cmd));
    switch_count = sum(diff_u > 2.0);

    %% Package Metrics Struct
    metrics = struct();
    metrics.controller_type = sim_data.controller_type;
    metrics.t_rise_sec      = t_rise;
    metrics.t_settle_sec    = t_settle;
    metrics.overshoot_pct   = overshoot_pct;
    metrics.ss_error_degC   = e_ss;
    metrics.IAE             = iae;
    metrics.ITAE            = itae;
    metrics.energy_Joules   = total_energy_J;
    metrics.energy_WattHours= total_energy_Wh;
    metrics.duty_cycle_pct  = duty_cycle_pct;
    metrics.switch_count    = switch_count;

end
